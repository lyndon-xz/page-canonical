/**
 * 一次取数在 UI 上的状态。
 *
 * 失败之所以要留在状态里、而不像操作类失败那样弹个 toast 了事：取数失败要把整块内容
 * 换成占位与重试入口，这依赖渲染分支。toast 三秒就散了，剩下一个空列表——用户既不知道
 * 发生过什么，也没有重试的地方，只能刷新整页。
 *
 * 用判别态而不是 `isLoading` + `hasError` 两个布尔：后者四种组合里「加载中且已失败」
 * 是非法的，得靠各处 action 手动维持互斥，一处漏清就会同时转圈又报错。
 *
 * 只表达「界面该显示什么」，不带失败原因：占位的文案是固定的，服务端消息没有出场的
 * 地方，存下来就是死值。原因属于日志与上报。
 */
export enum FetchStatus {
  Loading = "loading",
  Error = "error",
  /** 兼作初始值，语义是「没有进行中的请求，也没有失败」，此时显示什么由内容自身决定 */
  Ready = "ready",
}
